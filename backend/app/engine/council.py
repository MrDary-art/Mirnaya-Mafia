def evaluate_agreement(agreement: dict) -> dict:
    """Reveal these checks only after all four people approve one document version."""
    checks = [
        (agreement.get("first_batch_percent") == 40, "Первая партия должна составлять 40% заказа."),
        (agreement.get("first_batch_days") == 14, "Первую партию можно выпустить на 14-й день."),
        (agreement.get("balance_days") == 30, "Остаток заказа нужен клиенту к 30-му дню."),
        (20000 <= (agreement.get("extra_cost") or 0) <= 25000, "Ускорение требует от 20 000 до 25 000 ₽."),
        (agreement.get("prepayment_percent") == 30, "Финансирование возможно при предоплате 30%."),
        (bool((agreement.get("owner") or "").strip()), "Нужно назначить ответственного за исполнение."),
        (bool((agreement.get("decision") or "").strip()), "Нужно записать общее решение."),
    ]
    issues = [message for passed, message in checks if not passed]
    return {
        "feasible": not issues,
        "summary": "Команда согласовала выполнимый план двух поставок." if not issues else "Соглашение принято командой, но часть условий противоречит вводным.",
        "issues": issues,
        "role_facts": {key: {"name": role["name"], "private_facts": role["private_facts"], "limits": role["limits"]} for key, role in ROLES.items()},
    }
