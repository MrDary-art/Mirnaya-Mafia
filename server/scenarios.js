function listScenarios() {
  return SCENARIOS.map((s) => ({
    id: s.id,
    title: s.title,
    category: s.category,
    durationMin: s.durationMin,
    description: s.description,
    techniques: s.techniques,
    roles: s.roles.map((r) => ({
      id: r.id,
      name: r.name,
      publicBrief: r.publicBrief,
    })),
  }));
}

function getScenario(id) {
  return SCENARIOS.find((s) => s.id === id) || null;
}

function getRole(scenarioId, roleId) {
  const scenario = getScenario(scenarioId);
  if (!scenario) return null;
  return scenario.roles.find((r) => r.id === roleId) || null;
}

function opponentRole(scenario, roleId) {
  return scenario.roles.find((r) => r.id !== roleId) || scenario.roles[1];
}

module.exports = {
  SCENARIOS,
  listScenarios,
  getScenario,
  getRole,
  opponentRole,
};
